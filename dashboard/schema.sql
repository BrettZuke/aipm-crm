-- The dedupe index needs the track in it. Unique on (provider, external_id)
-- alone meant a coach webhook reusing an id the local book already held was
-- silently dropped as a duplicate: not a leak, but a lost write.
--
-- No WHERE clause, deliberately. Postgres will not accept a PARTIAL unique
-- index as an ON CONFLICT target, and both writers (api/activity.js and
-- api/go.js) upsert against this index. While it was partial every insert
-- was refused: logging a call or a DM answered "Could not log that
-- activity", and link-open tracking failed silently. A plain unique index
-- behaves the same way here anyway, because nulls are distinct, so rows with
-- no provider or no external_id still never collide.
drop index if exists activities_provider_external_idx;
drop index if exists activities_provider_external_track_idx;
create unique index if not exists activities_provider_external_track_idx
  on public.activities (provider, external_id, track);

-- Sample data (Settings, Data): every made-up row carries sample = true so
-- one delete removes them all and never touches a real lead. Idempotent.
do $$ declare t text; begin
  foreach t in array array['leads','coach_leads','activities','deals','tasks','referrals'] loop
    execute format('alter table public.%I add column if not exists sample boolean not null default false', t);
  end loop;
end $$;

-- Snooze (a lead hidden from the list and the runs until a day) and targets
-- (daily and weekly, per book, on the profile). Idempotent.
do $$ declare t text; begin
  foreach t in array array['leads','coach_leads'] loop
    execute format('alter table public.%I add column if not exists snooze_until date', t);
  end loop;
  foreach t in array array['profile'] loop
    execute format('alter table public.%I add column if not exists targets jsonb', t);
  end loop;
end $$;

-- Scripts: what a DM script is used for (open, pivot, bump, chase, no) and
-- whether it is a favourite (rises to the top, used first). Idempotent.
do $$ declare t text; begin
  foreach t in array array['scripts'] loop
    execute format('alter table public.%I add column if not exists use text not null default %L', t, '');
    execute format('alter table public.%I add column if not exists favourite boolean not null default false', t);
  end loop;
end $$;