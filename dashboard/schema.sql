-- The key outside software calls this CRM with, written when Settings rotates
-- it. It lives here rather than only in ACTIVITY_SECRET because a running
-- deployment cannot read a Vercel variable back to a screen and cannot change
-- one, so Settings had no key to show and no way to replace a leaked one.
-- api/activity.js and api/log.js accept this key or the variable, so an install
-- that never rotates keeps working on the variable alone.
alter table public.profile add column if not exists api_key text;

-- Replies (2026-09-14). reply_to is the address a prospect's answer comes back
-- to, which is rarely the address the mail went out from; it was the
-- RESEND_REPLY_TO variable, so changing your own inbox meant a redeploy.
-- inbound_secret is the signing secret Resend hands out for the webhook that
-- points at /api/inbound: every delivery is signed with it, and without one
-- that endpoint refuses everything rather than trusting a POST it cannot check.
-- Both are here for the same reason api_key is, and missing them does more than
-- turn replies off: api/profile.js writes reply_to on every save from Settings,
-- so a fresh install without these columns cannot save a profile at all.
alter table public.profile add column if not exists reply_to text;
alter table public.profile add column if not exists inbound_secret text;

-- ---------------------------------------------------------------------------
-- Two books of business: local businesses and online coaches (2026-09-12)
--
-- One database, one column. Every row belongs to exactly one track, and the
-- data layer filters on it in a single place, so the two can never show each
-- other's leads, money or activity. Existing rows default to 'local' because
-- that is all the CRM has ever held, which makes this migration a no-op for
-- anyone already running it.
--
-- Deliberately NOT tracked: profile (one person, one identity),
-- outreach_settings (sending caps belong to the mailbox, not the book),
-- lead_edits (it overlays Google Sheet rows, which are local by definition),
-- found_leads and sheet_cache (both part of the local scrape path).
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'deals','activities','tasks',
    'sequences','sequence_runs','emails','email_events',
    'scripts','saved_views',
    'templates','sites'
  ] loop
    if exists (select 1 from information_schema.tables
               where table_schema='public' and table_name=t) then
      execute format('alter table public.%I add column if not exists track text not null default ''local''', t);
      execute format('create index if not exists %I on public.%I (track)', t||'_track_idx', t);
    end if;
  end loop;
end $$;

