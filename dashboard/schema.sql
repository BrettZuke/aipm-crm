-- The short code on a found lead's tracked link. Defined before the table
-- that uses it as a default; the body only reads the table at call time.
create or replace function public.new_lead_code()
 returns text
 language plpgsql
as $function$
declare
  alphabet text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  code text;
  i int;
begin
  loop
    code := '';
    for i in 1..6 loop
      code := code || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1);
    end loop;
    -- Vanishingly unlikely at 32^6, but checked rather than assumed.
    exit when not exists (select 1 from public.found_leads where lead_code = code);
  end loop;
  return code;
end;
$function$;

