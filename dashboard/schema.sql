-- A built site, its proposal page and the template kit read the site's config
-- with the public anon key, so that one policy is the only public door in the
-- database: reading, and only the three columns a visitor of that site could
-- see anyway. The lead's email on the row stays out of reach of the public key.
revoke all on public.sites from anon;
grant select (slug, business, config) on public.sites to anon;
drop policy if exists sites_public_read on public.sites;
create policy sites_public_read on public.sites for select to anon using (true);
alter table public.sites enable row level security;

